    print(
        "Extracting batch quality metrics..."
    )

    metrics = extract_batch_metrics(
        report
    )

    print(
        f"   ✓ Metrics extracted from "
        f"{metrics['total_predictions']} predictions."
    )

    print()
    print(
        "Analyzing batch quality trend..."
    )

    # Only one batch report currently exists.
    # Do not invent historical data.
    trend = analyze_trend(
        current_metrics=metrics,
        previous_metrics=None
    )

