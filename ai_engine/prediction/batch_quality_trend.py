# HEALTH CLASSIFICATION
# ======================================================================================

def determine_confidence_health(
    confidence: float
) -> str:
    """Classify confidence health."""

    percentage = confidence * 100.0

    if percentage >= 80:
        return "HIGH"

    if percentage >= 60:
        return "MEDIUM"

    if percentage >= 40:
        return "LOW"

    return "VERY_LOW"


def determine_intelligence_health(
    intelligence: float
) -> str:
    """Classify intelligence health."""

    percentage = intelligence * 100.0

    if percentage >= 80:
        return "HIGH"

    if percentage >= 60:
        return "MEDIUM"

    if percentage >= 40:
        return "LOW"

    return "VERY_LOW"


def determine_operational_status(
    metrics: Dict[str, Any]
) -> str:
    """Determine overall health of the current batch."""

    quality_score = metrics["quality_score"]

    validation_score = metrics[
        "validation_score"
    ]

    valid_percentage = metrics[
        "valid_percentage"
    ]

    safety_status = str(
        metrics["safety_status"]
    ).upper()

    downstream_ready = metrics[
        "downstream_ready"
    ]

    if (
        quality_score >= 80
        and validation_score >= 95
        and valid_percentage >= 95
        and safety_status == "SAFE"
        and downstream_ready
    ):
        return "HEALTHY"

    if (
        quality_score >= 60
        and validation_score >= 90
        and valid_percentage >= 90
    ):
        return "MONITOR"

    return "ATTENTION_REQUIRED"


