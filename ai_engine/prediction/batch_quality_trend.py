# SAFE CONVERSION HELPERS
# ======================================================================================

def safe_float(
    value: Any,
    default: float = 0.0
) -> float:
    """Safely convert a value to float."""

    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def safe_int(
    value: Any,
    default: int = 0
) -> int:
    """Safely convert a value to integer."""

    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def clamp(
    value: float,
    minimum: float,
    maximum: float
) -> float:
    """Clamp a numeric value inside a valid range."""

    return max(
        minimum,
        min(value, maximum)
    )


# ======================================================================================
# JSON LOADING
# ======================================================================================

def load_json_file(
    file_path: Path
) -> Dict[str, Any]:
    """
    Load a JSON object from disk.

    Raises
    ------
    FileNotFoundError
        If the file does not exist.

    ValueError
        If the file contains invalid JSON or an unexpected structure.
    """

    if not file_path.exists():
        raise FileNotFoundError(
            f"Required file not found: {file_path}"
        )

    try:
        with file_path.open(
            "r",
            encoding="utf-8"
        ) as file:
            data = json.load(file)

    except json.JSONDecodeError as exc:
        raise ValueError(
            f"Invalid JSON file: {file_path}\n"
            f"JSON error: {exc}"
        ) from exc

    if not isinstance(data, dict):
        raise ValueError(
            f"Expected a JSON object in {file_path}, "
            f"but received {type(data).__name__}."
        )

    return data


