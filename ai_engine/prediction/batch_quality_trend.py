# ======================================================================================
# TREND ANALYSIS
# ======================================================================================

def analyze_trend(
    current_metrics: Dict[str, Any],
    previous_metrics: Optional[Dict[str, Any]] = None
) -> Dict[str, Any]:
    """
    Compare current batch metrics with a previous batch.

    When no previous batch exists, return a baseline result.
    """

    if previous_metrics is None:
        return create_baseline_analysis(
            current_metrics
        )

    quality_change = calculate_change(
        current_metrics["quality_score"],
        previous_metrics["quality_score"]
    )

    validation_change = calculate_change(
        current_metrics["validation_score"],
        previous_metrics["validation_score"]
    )

    confidence_change = calculate_change(
        current_metrics["average_confidence_score"],
        previous_metrics["average_confidence_score"]
    )

    intelligence_change = calculate_change(
        current_metrics["average_intelligence_score"],
        previous_metrics["average_intelligence_score"]
    )

    valid_percentage_change = calculate_change(
        current_metrics["valid_percentage"],
        previous_metrics["valid_percentage"]
    )

    invalid_percentage_change = calculate_change(
        current_metrics["invalid_percentage"],
        previous_metrics["invalid_percentage"]
    )

    critical_risk_change = (
        current_metrics["critical_risk"]
        - previous_metrics["critical_risk"]
    )

    delayed_prediction_change = (
        current_metrics["delayed"]
        - previous_metrics["delayed"]
    )

    degradation_reasons: List[str] = []

    if quality_change < -1.0:
        degradation_reasons.append(
            "Overall batch quality score decreased."
        )

    if validation_change < -1.0:
        degradation_reasons.append(
            "Validation score decreased."
        )

    if confidence_change < -0.02:
        degradation_reasons.append(
            "Average prediction confidence decreased."
        )

    if intelligence_change < -0.02:
        degradation_reasons.append(
            "Average AI intelligence score decreased."
        )

    if invalid_percentage_change > 1.0:
        degradation_reasons.append(
            "Invalid prediction percentage increased."
        )

    if critical_risk_change > 0:
        degradation_reasons.append(
            "Critical-risk prediction count increased."
        )

    if delayed_prediction_change > 0:
        degradation_reasons.append(
            "Delayed prediction count increased."
        )

    degradation_detected = bool(
        degradation_reasons
    )

    if degradation_detected:
        trend_status = "DEGRADING"

    elif quality_change > 1.0:
        trend_status = "IMPROVING"

    else:
        trend_status = "STABLE"

    if quality_change > 1.0:
        trend_direction = "INCREASING"

    elif quality_change < -1.0:
        trend_direction = "DECREASING"

    else:
        trend_direction = "STABLE"

    return {
        "trend_status": trend_status,

        "trend_direction": trend_direction,

        "previous_batch_available": True,

        "quality_score_change": quality_change,

        "quality_score_percentage_change": calculate_percentage_change(
            current_metrics["quality_score"],
            previous_metrics["quality_score"]
        ),

        "validation_score_change": validation_change,

        "confidence_change": confidence_change,

        "intelligence_change": intelligence_change,

        "valid_percentage_change": valid_percentage_change,

        "invalid_percentage_change": invalid_percentage_change,

        "critical_risk_change": critical_risk_change,

        "delayed_prediction_change": delayed_prediction_change,

        "degradation_detected": degradation_detected,

        "degradation_reasons": degradation_reasons,
    }


