# CHANGE CALCULATIONS
# ======================================================================================

def calculate_change(
    current: float,
    previous: float
) -> float:
    """Calculate absolute change."""

    return round(
        current - previous,
        4
    )


def calculate_percentage_change(
    current: float,
    previous: float
) -> float:
    """Calculate percentage change."""

    if previous == 0:
        return 0.0

    return round(
        (
            (current - previous)
            / abs(previous)
        ) * 100.0,
        2
    )


